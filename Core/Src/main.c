int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MPU Configuration--------------------------------------------------------*/
  MPU_Config();

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* Configure the system clock */
  SystemClock_Config();

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_USART3_UART_Init();
  MX_LWIP_Init();
  /* USER CODE BEGIN 2 */

  if (netif_is_link_up(&gnetif))
  {
      DebugUART_Print("ETH link: UP\r\n");
  }
  else
  {
      DebugUART_Print("ETH link: DOWN\r\n");
  }

  /* Дадим DHCP немного времени */
  //HAL_Delay(1000);

  DebugUART_Print("IP: %s\r\n", ipaddr_ntoa(&gnetif.ip_addr));
  DebugUART_Print("MASK: %s\r\n", ipaddr_ntoa(&gnetif.netmask));
  DebugUART_Print("GW: %s\r\n", ipaddr_ntoa(&gnetif.gw));

  //RawTcpServer_Init();  //запуск сервера
  static uint8_t tcp_started = 0;

  /* USER CODE END 2 */
  while (1)
  {
	  MX_LWIP_Process();
	  if (!tcp_started && netif_is_link_up(&gnetif))
	      {
	          tcp_started = 1;
	          DebugUART_Print("[TCP] Starting TCP server\r\n");
	          RawTcpServer_Init();
	      }
  }
}

